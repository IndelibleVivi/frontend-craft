// Playwright CLI callback. Open the generated examples/catalog project fixture first.
async page => {
  const base = new URL('./', page.url()).href;
  const origin = new URL(base).origin;
  const checks = [];
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('request', request => requests.push(request.url()));
  function check(ok, label) { if (!ok) throw new Error(label); checks.push(label); }
  async function shown(selector) { return page.locator(selector).isVisible(); }
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto(base);
  check(await page.locator('.card:visible').count() === 3, 'All three recorded items shown');
  await page.locator('[data-role="style"]').click();
  await page.locator('#search').fill('margin');
  check(await page.locator('.card:visible').count() === 1, 'Role and search compose');
  check(new URL(page.url()).searchParams.get('role') === 'style', 'Filters enter the URL');
  await page.locator('.card:visible .open').click();
  check(page.url().includes('#item='), 'Detail is an exact-identity deep link');
  await page.reload();
  check(await shown('#detail'), 'Reload reopens the selected exact record');
  check(new URL(page.url()).searchParams.get('q') === 'margin', 'Reload preserves query');
  const referenceKey = await page.locator('#detail .refs a[data-item-link]').first().getAttribute('data-focus-key');
  await page.locator('#detail .refs a[data-item-link]').first().click();
  check(await page.locator('#detail [data-selector="asset:web-subset"]').count() === 1, 'Material link locates its exact asset');
  check(await page.evaluate(() => document.activeElement.dataset.selector) === 'asset:web-subset', 'Material selector receives focus');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#detail a[download]').click();
  const download = await downloadPromise;
  check(download.suggestedFilename().endsWith('.woff2'), 'Actual material download retains font suffix');
  await page.goBack();
  check((await page.locator('#detail .detail-title .meta').innerText()).includes('reading-margin@2'), 'Browser Back returns to the source record');
  await page.waitForFunction(key => document.activeElement.dataset.focusKey === key, referenceKey);
  check((await page.evaluate(() => document.activeElement.dataset.focusKey || '')).includes('sample-title-font'), 'Back restores reference-link focus');
  await page.goForward();
  check((await page.locator('#detail .detail-title .meta').innerText()).includes('sample-title-font@1'), 'Forward reopens the exact material revision');
  await page.goBack();
  await page.waitForFunction(key => document.activeElement.dataset.focusKey === key, referenceKey);
  check((await page.locator('#detail .detail-title .meta').innerText()).includes('reading-margin@2'), 'Repeated history traversal preserves source context');
  await page.locator('#detail .history-list a').filter({hasText: 'rev 1'}).click();
  check((await page.locator('#detail .detail-title .meta').innerText()).includes('@1'), 'History opens revision one');
  const historicalURL = page.url();
  await page.reload();
  check(page.url() === historicalURL && (await page.locator('#detail .detail-title .meta').innerText()).includes('@1'), 'Historical revision survives reload');
  const resultOption = await page.locator('#compare option').evaluateAll(options => options.find(option => option.textContent.includes('reader-result@1')).value);
  await page.locator('#compare').selectOption(resultOption);
  check(await page.locator('.compare-pane').count() === 2, 'Two exact records compare side by side');
  await page.reload();
  check(await page.locator('.compare-pane').count() === 2, 'Comparison survives reload');
  await page.locator('#detail button.zoom').first().click();
  await page.locator('#ui-language').click();
  check(await page.locator('html').getAttribute('lang') === 'zh-CN', 'Chinese UI is available');
  check(await page.locator('.compare-pane').count() === 2 && await page.locator('.preview-viewport.original').count() === 1, 'Language preserves comparison and original-size inspection');
  await page.setViewportSize({width: 390, height: 844});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow comparison has no horizontal page overflow');
  await page.setViewportSize({width: 1440, height: 1000});
  await page.locator('[data-collection-link]').click();
  check(await page.locator('#search').inputValue() === 'margin' && await page.locator('.card:visible').count() === 1, 'Returning to collection retains filters');
  await page.locator('#search').fill('no-such-record');
  check(await shown('#empty'), 'No-match state stays actionable');
  await page.locator('#clear-filters').click();
  check(await page.locator('.card:visible').count() === 3, 'Clear restores all records');
  await page.goto(base + '#item=unavailable-revision');
  check(await page.locator('#detail .notice').count() === 1, 'Unknown exact record reports a gap');
  await page.locator('#detail-back').click();
  check(await shown('#collection'), 'Fresh deep-link Back stays in this gallery');
  const first = page.locator('.card .open').first();
  const firstKey = await first.getAttribute('data-focus-key');
  await first.focus(); await page.keyboard.press('Enter'); await page.keyboard.press('Escape');
  await page.waitForFunction(key => document.activeElement.dataset.focusKey === key, firstKey);
  check(await shown('#collection'), 'Keyboard activation/Escape restores the opener');
  await page.locator('#ui-language').click();
  await page.setViewportSize({width: 390, height: 844});
  await page.waitForFunction(() => !document.getElementById('current-uses').open);
  check(!(await page.locator('#current-uses').evaluate(el => el.open)), 'Compact collection gives previews priority');
  await page.locator('#current-uses > summary').focus();
  await page.keyboard.press('Enter');
  check(await page.locator('#current-uses .use').first().isVisible(), 'Compact adoption records remain keyboard-accessible');
  await page.locator('#current-uses > summary').click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow collection has no horizontal page overflow');
  check(errors.length === 0, 'No browser page errors');
  check(requests.every(url => new URL(url).origin === origin), 'Gallery makes no external requests');
  return {checks, errors, externalRequests: requests.filter(url => new URL(url).origin !== origin)};
}
